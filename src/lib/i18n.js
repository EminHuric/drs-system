export function applyRestaurantLocale(restaurantLocale) {
  if (locale.value) return // gost je već izabrao — njegov izbor je jači
  locale.value = dict[restaurantLocale] ? restaurantLocale : 'sr'
}

export function setLocale(code) {
  if (!dict[code]) return
  locale.value = code
  try {
    localStorage.setItem(KEY, code)
  } catch {
    /* privatni režim */
  }
}

/** Prevod; ako ključ nedostaje u jeziku, pada na srpski pa na sam ključ. */
export function t(key) {
  const l = dict[locale.value] || dict.sr
  return l[key] ?? dict.sr[key] ?? key
}

export const currentLocale = computed(() => LOCALES[locale.value] || LOCALES.sr)
